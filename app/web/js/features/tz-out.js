// ТЗ на сборку станции в контейнере — для субподрядчика (сборщика контейнера), документ Word. Сторона поставки — как в
// «Составе станции» (KitScope): наше оборудование (компрессоры, ДГУ, насосы, осушители, фильтры, ресиверы) — давальческое,
// сборщик поставляет контейнер, его системы, шкафы, трубопровод, обвязку и всё, что отвечает за безопасность. В ТЗ:
// контейнер и системы (с оценкой отопления и вентиляции), перечни, привязки оборудования по габаритному чертежу, трубопроводы
// и схема, электрика, нормы, испытания, документы, отгрузка; приложения — габаритный чертёж, схема, 3D-вид. Имени
// заказчика станции в ТЗ нет — только требования.
'use strict';

class TzOut {
  static N = v=>StationLayout.n(v);
  static NAME = s=>String(s||'').replace(/[\\/:*?"<>|]+/g, ' ').replace(/\s+/g, ' ').trim().slice(0, 80);

  /** скачать ТЗ на сборку станции (позиция i) */
  static async download(i){
    const x=S.items[i]; if (!x || !stationOf(x) || !isKit(x)) return toast('ТЗ на сборку — для станции в контейнере с составом');
    toast('Готовлю ТЗ на сборку…');
    try{ const b=await this.make(x); saveFileA(`ТЗ на сборку — ${this.NAME(x.name) || 'станция'}${S.number ? ' — КП '+this.NAME(S.number) : ''}.docx`, b); }
    catch(e){ toast('Не удалось подготовить ТЗ на сборку: '+(e && e.message || e)); }
  }

  /** документ .docx (Blob) */
  static async make(x){
    await EskdFont.load(); if (typeof DrawPic!=='undefined') await DrawPic.load(x);
    const plan=StationUi.plan(x), meta=StationUi.meta(x, plan), org=StationUi.org(), d=new DocxWriter({ title:'ТЗ на сборку: '+(x.name||''), author:org, footer:'ТЗ на сборку — '+(x.name||'станция') });
    this.write(d, x, plan, org);
    // приложения: габаритный чертёж, схема, 3D-вид
    const ok=plan.level!=='error' && plan.geo && plan.geo.ext, sch=ok ? StationUi.scheme(plan) : null; let n=0;
    if (ok){ d.h1('Приложения', true);
      const add=(im, cap, maxH, page)=>{ if (im && im.src) d.image(im.src, im.w, im.h, d.width, `Приложение ${++n}. ${cap}`, maxH, page); };
      add(await StationImages.raster(StationDrawing.svg(plan, meta), 'image/png'), 'Габаритный чертёж', 225, false);
      if (sch) add(await StationImages.raster(sch.cls.svg(plan, meta), 'image/png'), sch.name, 240, true);
      const gl=await StationRender.image(plan, meta), v3=gl || await StationImages.raster(StationView3D.svg(plan, meta), 'image/jpeg');
      add(v3, '3D-вид (стены со стороны зрителя срезаны)', 200, true); }
    return d.pack('blob');
  }

  /** текст ТЗ: разделы по порядку */
  static write(d, x, plan, org){
    const parts=kitParts(x), c=kitContainer(x)||{}, eq=StationEquip.list(parts), pos=new Map(eq.filter(e=>e.pos).map(e=>[e.id, e])), req=StationReq.plan(x), r=StationReq.of(x);
    const kind={ comp:'компрессорная станция', dgu:'дизель-генераторная электростанция', pump:'насосная станция' }[req.kind] || 'станция';
    const mgr=S.manager||{}, ok=plan.level!=='error' && plan.geo && plan.geo.ext;
    d.title1('Техническое задание на сборку станции в контейнере');
    d.p([[x.name||'Станция', { b:true }]], { align:'center', after:2 });
    d.p(`${org}${S.number ? ' · КП № '+S.number : ''}${S.date ? ' от '+EskdSheet.date(S.date) : ''}`, { align:'center', after:10, run:{ color:'555555' } });

    d.h1('1. Общие сведения');
    const ln=StationReq.line(Object.assign({}, x, { req:Object.assign({}, r, { src:null }) }));   // без имени файла ТЗ заказчика
    d.items([
      [['Изделие: ', { b:true }], [`${x.name||'станция'} — ${kind} в контейнере.`, {}]],
      ...(ln ? [[['Параметры станции: ', { b:true }], [ln+'.', {}]]] : []),
      [['Заказчик сборки: ', { b:true }], [`${org}${mgr.name ? `, ответственный — ${mgr.name}${mgr.phone ? ', '+mgr.phone : ''}${mgr.email ? ', '+mgr.email : ''}` : ''}.`, {}]],
      [['Сборщик: ', { b:true }], [`${String(c.sup||'').trim() || 'изготовитель контейнера'} — изготавливает контейнер с системами, принимает и монтирует оборудование заказчика, поставляет и монтирует шкафы, трубопроводы, обвязку и оборудование безопасности, испытывает станцию и сдаёт её заказчику.`, {}]],
      'Отступления от ТЗ, замена материалов и оборудования сборщика — только по письменному согласованию с заказчиком.',
      'Размеры, привязки и трассы уточняются рабочей документацией сборщика и согласуются с заказчиком до начала работ.',
    ], '1.');

    // ---- 2. контейнер
    d.h1('2. Контейнер и его системы');
    const ct=ctypeOf(c.ctype), cl=CLIMATES.find(z=>z[0]===c.climate), sys=c.sys||{}, n=this.N;
    const dims=ok ? `наружные ${n(plan.geo.ext[0])} × ${n(plan.geo.ext[1])} × ${n(plan.geo.ext[2])} мм, внутри ${n(plan.int[0])} × ${n(plan.int[1])} × ${n(plan.int[2])} мм` : (String(c.size||'').trim() || ct.size);
    d.table([42, 128], ['Параметр', 'Требование'], [
      ['Тип', ct.name], ['Размеры (Д × Ш × В)', dims],
      ['Утепление', c.ins ? 'минеральная вата '+c.ins+', пароизоляция, внутренняя обшивка' : 'по типу контейнера'],
      ['Климатическое исполнение', cl ? `${cl[0]} по ГОСТ 15150-69 (${cl[1]})` : 'по ГОСТ 15150-69 — по месту установки'],
      ['Наружный воздух', [req.tmin!=null ? 'от '+StationNorms.deg(req.tmin) : '', req.tmax!=null ? 'до '+StationNorms.deg(req.tmax) : ''].filter(Boolean).join(' ') || 'по месту установки'],
      ['Окраска', String(c.ral||'').trim() || 'по согласованию'],
      ['Двери', this.doors(plan)],
      ...CONT_SYSTEMS.filter(([id])=>sys[id]).map(([id, k, v])=>[k, this.sysText(id, v, plan, req, c)]),
    ]);
    const off=CONT_SYSTEMS.filter(([id])=>!sys[id]).map(([, k])=>k.toLowerCase());
    if (off.length) d.p(`Не требуются (не входят в поставку): ${off.join(', ')}.`, { after:6, run:{ color:'555555' } });

    // ---- 3. наше оборудование
    d.h1('3. Оборудование заказчика (давальческое)');
    const our=parts.filter(p=>p.role!=='container' && KitScope.of(p)==='our'), asm=parts.filter(p=>p.role!=='container' && KitScope.of(p)==='asm');
    d.p(`Поставляет ${org} на площадку сборщика; приёмка — по количеству и внешнему виду, по акту. До монтажа — хранить в упаковке, в сухом помещении; консервацию не снимать.`);
    if (our.length) d.table([12, 70, 12, 44, 20, 22], ['Поз.', 'Наименование', 'Кол.', 'Габариты Д × Ш × В, мм', 'Масса, кг', 'Мощность, кВт'],
      our.map(p=>{ const e=pos.get(p.id)||{}, kw=StationEquip.num((p.attrs||{}).kw);
        return [String(e.pos||'—'), p.name||'', String(p.qty||1), e.known ? `${n(e.l)} × ${n(e.w)} × ${n(e.h)}` : 'по паспорту', e.mass>0 ? n(e.mass) : '—', kw>0 ? String(kw).replace('.', ',') : '—']; }));
    else d.p('Нет — всё оборудование поставляет сборщик.');

    // ---- 4. поставка и работы сборщика
    d.h1('4. Поставка и работы сборщика');
    if (asm.length) d.table([12, 58, 12, 88], ['Поз.', 'Наименование', 'Кол.', 'Требования'], asm.map(p=>{ const e=pos.get(p.id)||{};
      return [String(e.pos||'—'), p.name||'', String(p.qty||1), this.asmText(p, e)]; }));
    d.items([
      'Монтаж оборудования заказчика по габаритному чертежу (приложение 1) и инструкциям изготовителей: на раму или анкерами к полу, с виброопорами, где они предусмотрены; на время перевозки — транспортное крепление.',
      'Трубопроводная обвязка, запорная и предохранительная арматура, манометры — по схеме (приложение 2) и разделу 6.',
      'Электромонтаж: питание оборудования от шкафов, кабели в лотках и гофре, заземление и уравнивание потенциалов — по разделу 7.',
      'Проходы обслуживания и отступы оборудования от стен — не меньше указанных на чертеже: оборудование обслуживается без демонтажа соседнего.',
      'Пусконаладка — совместно с заказчиком после монтажа; до неё оборудование заказчика не включать.',
    ], '4.');

    // ---- 5. размещение
    if (ok){ d.h1('5. Размещение оборудования');
      d.p(`Привязки — от внутренних поверхностей стен до ближнего края оборудования: X — от левого торца${plan.door==='side' ? ' (со стороны входной двери)' : ''}, Y — от передней стены${plan.door==='side' ? ' (с дверью)' : ''}; Z — от пола до низа. Допуск ±50 мм; иное — по согласованию.`);
      const I=[...plan.items].sort((a, b)=>a.pos-b.pos || a.unit-b.unit), out=plan.outside||[], mt=i=>i.mount==='wall' ? 'на стене' : i.mount==='pipe' ? 'на трубопроводе' : i.mount==='frame' ? 'на раме' : 'на полу';
      d.table([12, 66, 20, 20, 20, 32], ['Поз.', 'Наименование', 'X, мм', 'Y, мм', 'Z, мм', 'Установка'], [
        ...I.map(i=>[String(i.pos), (i.short||i.name||'')+(i.unit ? ` (${i.unit+1})` : ''), n(i.x), n(i.y), n(i.z||0), mt(i)]),
        ...out.map(i=>[String(i.pos), (i.short||i.name||'')+(i.unit ? ` (${i.unit+1})` : ''), '—', '—', '—', `снаружи, ${n(StationLayout.OUT_GAP)} мм от дальнего торца, на площадке`])]);
      const iss=plan.issues.filter(t=>t.level==='warn').map(t=>t.text);
      if (iss.length){ d.h2('Учесть при сборке'); d.items(iss, '5.'); } }

    // ---- 6. трубопроводы
    d.h1(`${ok ? 6 : 5}. Трубопроводы и арматура`);
    const pp=(plan.piping||[]).find(q=>q.pos!=null), mat=pp && PipeMaterial.get(pp.mat), med=req.kind==='comp' ? 'сжатый воздух' : req.kind==='pump' ? 'вода' : req.kind==='dgu' ? 'дизельное топливо' : 'рабочая среда';
    const bar=plan.air && plan.air.bar>0 ? plan.air.bar : null;
    d.items([
      `Среда — ${med}${bar ? `, рабочее давление ${String(bar).replace('.', ',')} бар` : ''}; материал труб — ${mat ? mat.row : 'сталь (согласовать)'}${pp && pp.dn ? ', '+pp.dn : ''}; соединения — сварные или фланцевые, резьбовые — у арматуры.`,
      req.kind==='comp' ? 'Сжатый воздух — последовательно по схеме: у ресивера, осушителя и фильтров один вход и один выход; уклон линий — к сборникам конденсата, отвод конденсата — в масловодоотделитель или дренаж.' : '',
      req.kind==='pump' ? 'Насосы — параллельно между всасывающим и напорным коллекторами; на каждом — задвижки до и после, обратный клапан на напоре, манометры.' : '',
      req.kind==='dgu' ? 'Топливопровод — сталь, без полимерных вставок; подключение бака — с запорным клапаном, у ДГУ — гибкие подводки изготовителя.' : '',
      'Испытания трубопроводов на прочность и плотность — 1,25 рабочего давления (ГОСТ 32569-2013), с протоколом; затем продувка (промывка).',
      'Опознавательная окраска и маркировка — по ГОСТ Р 71918-2024, стрелки направления потока.',
      ...(plan.outside||[]).length ? ['Ресивер снаружи: бетонная площадка с выступом 200 мм, трубопровод через стену в гильзе, запорная арматура у стены внутри; предохранительный клапан и манометр — на ресивере.'] : [],
    ], (ok ? 6 : 5)+'.');

    // ---- 7. электрика
    d.h1(`${ok ? 7 : 6}. Электрооборудование`);
    const kw=eq.filter(e=>e.place && e.kw>0 && /^(compressor|pump|dryer)$/.test(e.kind)).reduce((s, e)=>s+e.kw*e.qty, 0);
    d.items([
      kw ? `Установленная мощность оборудования заказчика — около ${n(kw)} кВт (плюс собственные нужды контейнера); ввод и шкафы — с запасом по току пуска.` : '',
      'Шкафы — на местах по чертежу; проход перед шкафами — не менее 800 мм (ПУЭ, п. 4.1.23), щит длиннее 7 м — с двумя выходами; двери электропомещения открываются наружу (п. 4.2.94).',
      'Заземление и уравнивание потенциалов оборудования, трубопроводов и металлоконструкций контейнера — по ПУЭ, гл. 1.7; болт заземления снаружи контейнера.',
      'Кабели — с медными жилами, не распространяющие горение (нг(А)-LS); вводы — сальниковые, герметичные.',
      'Шкафы управления — с декларациями ТР ТС 004/2011 и 020/2011, схемами и паспортами.',
    ], (ok ? 7 : 6)+'.');

    // ---- 8. нормы
    d.h1(`${ok ? 8 : 7}. Безопасность и нормы`);
    d.items([
      ok ? StationNorms.tt(plan)[0] : `Категория помещения по пожарной опасности — ${req.fire}${req.fireAuto ? ' (ориентировочно, уточняется расчётом по СП 12.13130.2009)' : ' (СП 12.13130.2009)'}; табличка с категорией — на двери снаружи.`,
      `Уровень звука на рабочем месте — не более ${req.noise} дБА (СанПиН 1.2.3685-21); выше — шумоизоляция контейнера и знак о средствах защиты слуха.`,
      ...(ok ? StationDrawing.vessels(plan) : []),
      `Климатическое исполнение контейнера${cl ? ' — '+cl[0] : ''} по ГОСТ 15150-69; внутри при работе — не ниже +${StationNorms.INSIDE} °C, оборудование — в исполнении для отапливаемых помещений.`,
      r.notes ? 'Требования заказчика станции: '+String(r.notes).trim() : '',
    ], (ok ? 8 : 7)+'.');

    // ---- 9. испытания и приёмка
    d.h1(`${ok ? 9 : 8}. Испытания и приёмка`);
    d.items([
      'Перед отгрузкой: испытания трубопроводов, измерение сопротивления изоляции кабелей, проверка металлосвязи (заземления), проверка освещения, отопления, вентиляции, сигнализации — с протоколами.',
      'Приёмка — на площадке сборщика с участием заказчика: внешний осмотр, соответствие чертежу и ТЗ, протоколы; замечания устраняются до отгрузки.',
      'Фотоотчёт о монтаже (общий вид, узлы обвязки, шкафы, заземление) — с документами.',
    ], (ok ? 9 : 8)+'.');

    // ---- 10. документы
    d.h1(`${ok ? 10 : 9}. Документы от сборщика`);
    d.items([
      'Паспорт контейнера (блок-контейнера) и руководство по эксплуатации его систем.',
      'Исполнительные схемы: трубопроводов, электрическая принципиальная, расположения оборудования.',
      'Протоколы испытаний (раздел выше), акт приёмки.',
      'Декларации (сертификаты) соответствия, паспорта на оборудование и материалы сборщика (шкафы, арматура, кабели, огнетушители).',
    ], (ok ? 10 : 9)+'.');

    // ---- 11. отгрузка
    d.h1(`${ok ? 11 : 10}. Упаковка и отгрузка`);
    const mass=ok ? [...plan.items, ...(plan.outside||[])].reduce((s, i)=>s+(i.mass>0 ? i.mass : 0), 0) : 0;
    d.items([
      'Оборудование и шкафы закреплены на время перевозки; двери, люки и жалюзи закрыты и опломбированы; открытые патрубки заглушены.',
      plan.roof && plan.roof.length ? 'Глушитель ДГУ на время перевозки снимается и закрепляется внутри; выхлоп на крыше — заглушка от осадков.' : '',
      (plan.outside||[]).length ? 'Ресивер снаружи перевозится отдельно, с заглушками на патрубках.' : '',
      `Строповочные узлы — по схеме строповки сборщика${mass ? `; масса оборудования заказчика — около ${n(mass)} кг (без контейнера)` : ''}.`,
    ], (ok ? 11 : 10)+'.');
  }

  /** двери по расстановке */
  static doors(plan){
    if (plan.door==='service') return `сервисные — ${(plan.doors||[]).length} шт. напротив оборудования (обслуживание снаружи), утеплённые, с замками и фиксаторами`;
    if (plan.door==='end') return 'двери (ворота) в торце — штатные, утеплённые';
    return `входная — ${this.N(StationLayout.ENTRY[1]-StationLayout.ENTRY[0])} мм (не менее 600 мм в свету), утеплённая, открывается наружу, с замком и доводчиком`;
  }
  /** система контейнера: текст требования (отопление и вентиляция — с оценкой мощности и расхода) */
  static sysText(id, v, plan, req, c){
    const n=this.N;
    if (id==='heat' && plan.geo && plan.geo.ext){
      const [L, W, H]=plan.geo.ext.map(q=>q/1000), A=2*(L*W+L*H+W*H), ins=StationGeo.ins(c.ins)/1000, U=0.04/Math.max(0.04, ins)*1.3, t=req.tmin!=null ? req.tmin : -40;
      const kW=Math.max(1, Math.ceil(U*A*(StationNorms.INSIDE-t)/100)/10);
      return `${v}; внутри не ниже +${StationNorms.INSIDE} °C; мощность — не менее ${String(kW).replace('.', ',')} кВт (теплопотери при ${StationNorms.deg(t)} снаружи, без тепла оборудования)`;
    }
    if (id==='vent'){
      const heat=(plan.items||[]).filter(i=>i.kind==='compressor' && i.kw>0).reduce((s, i)=>s+i.kw*0.9, 0);
      if (heat>0){ const m3=Math.ceil(heat*3600/(1.2*1.005*10)/100)*100;
        return `${v}; тепло компрессоров — около ${n(heat)} кВт: расход — не менее ${n(m3)} м³/ч при нагреве воздуха на 10 °C (или горячий воздух компрессоров — воздуховодами наружу, по паспортам); зимой — рециркуляция, без переохлаждения`; }
      if ((plan.items||[]).some(i=>i.kind==='dgu')) return `${v}; воздух на горение и охлаждение ДГУ — по паспорту ДГУ (жалюзи с электроприводом напротив радиатора, воздуховод радиатора)`;
    }
    if (id==='fire') return `${v}; по СП 486.1311500.2020, с выводом сигнала на пульт`;
    return v;
  }
  /** требования к элементу сборщика: описание или главные характеристики */
  static asmText(p, e){
    const rows=(p.rows||[]).filter(q=>q && q.k && q.v).slice(0, 4).map(q=>`${q.k} — ${q.v}`), mat=PipeMaterial.of(p), desc=String(p.desc||'').trim();
    const t=[desc ? (desc.length>220 ? desc.slice(0, 219).replace(/\s+\S*$/, '')+'…' : desc) : '', rows.join('; '), mat ? 'материал — '+mat.row : '', e.kind==='cabinet' ? `установка — ${e.mount==='floor' ? 'на полу' : 'на стене'}` : ''].filter(Boolean);
    return t.join('. ') || 'по согласованию с заказчиком';
  }
}
