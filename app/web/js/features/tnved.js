  // код для позиции: {code, duty ('' — ставка не подтверждена), ok, name, note, alt:{code, duty, name}} или null (категория без правила)
  static pick(x, a, cat){
    x=x||{}; a=a||{}; cat=cat||(x.role==='container'?'container':a.cat);
    const code=TnVed.codeOf(x, a, cat);
    if (code==null) return null;
    const note=(TnVed.CATS[cat]||[])[1]||'';
    if (code==='') return {code:'', duty:'0', ok:1, name:'Услуга', note, alt:null};
    const c=TnVed.CODES[code]||{name:'', duty:null, ok:0}, alt=TnVed.ALT[code], ac=alt&&TnVed.CODES[alt];
    return {code, duty:TnVed.dutyText(c.duty), ok:c.ok, name:c.name, note, alt: ac ? {code:alt, duty:TnVed.dutyText(ac.duty), name:ac.name} : null};
  }

