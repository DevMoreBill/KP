  static FEE_TITLE = 'ПП РФ № 1637 в ред. № 1638, с 01.01.2026';
  static HALF = 2;
  static ABOVE = 1.5;

  /**
   * Значение из «Значений программы» или запасное.
   * @param {string} key
   * @param {number} fallback
   * @returns {number}
   */
  static num(key, fallback) {
    return DefRegistry.num(key, fallback);
  }

  /**
   * Шкала сбора из «Значений программы»; границы не по возрастанию — встроенная шкала.
   * @returns {number[][]}
   */
  static feeScale() {
    const builtin = this.FEE;
    const last = builtin.length - 1;
    const out = builtin.map(([limit, fee], i) => [
      i < last ? this.num(`deal.feeLim${i + 1}`, limit) : Infinity,
      this.num(`deal.fee${i + 1}`, fee),
    ]);
    for (let i = 1; i < out.length; i++) if (!(out[i][0] > out[i - 1][0])) return builtin.map(row => [...row]);
    return out;
  }

  /**
   * Шкала изменена администратором.
   * @returns {boolean}
   */
  static feeOwn() {
    return this.feeScale().some((row, i) => row[0] !== this.FEE[i][0] || row[1] !== this.FEE[i][1]);
  }

  /**
   * Целые рубли текстом.
   * @param {number} value
   * @returns {string}
   */
  static rub(value) {
    return Money.int(value);
  }

  /**
   * Шкала текстом: «до 200 000 ₽ — 1 231 ₽, …, свыше 10 000 000 ₽ — 73 860 ₽».
   * @returns {string}
   */
  static feeText() {
    const scale = this.feeScale();
    return scale
      .map(([limit, fee], i) => {
        const band = limit === Infinity ? `свыше ${this.rub(scale[i - 1][0])}` : `до ${this.rub(limit)}`;
        return `${band} ₽ — ${this.rub(fee)} ₽`;
      })
      .join(', ');
  }

  /**
   * Таможенный сбор по таможенной стоимости.
   * @param {number} value таможенная стоимость, ₽
   * @returns {number}
   */
  static fee(value) {
    if (!(value > 0)) return 0;
    for (const [limit, fee] of this.feeScale()) if (value <= limit) return fee;
    return 0;
  }

  /**
   * Интервал шкалы для подсказки: «таможенная стоимость 3 100 000 ₽ → интервал 2 700 000,01 – 4 200 000 ₽ → сбор …».
   * @param {number} value
   * @returns {string}
   */
  static feeBand(value) {
    if (!(value > 0)) return '';
    const scale = this.feeScale();
    const i = scale.findIndex(row => value <= row[0]);
    if (i < 0) return '';
    const fmt = number => Money.int(number);
    const low = i ? `${fmt(scale[i - 1][0])},01` : '0';
    const high = scale[i][0] === Infinity ? 'и выше' : `– ${fmt(scale[i][0])}`;
    return `таможенная стоимость ${fmt(value)} ₽ → интервал ${low} ${high} ₽ → сбор ${fmt(scale[i][1])} ₽`;
  }

  static _example(i) {
    const builtin = this.FEE;
    const last = builtin.length - 1;
    if (!i) return builtin[0][0] / this.HALF;
    return i < last ? (builtin[i - 1][0] + builtin[i][0]) / this.HALF : builtin[i - 1][0] * this.ABOVE;
  }

  static _feeRows() {
    const builtin = this.FEE;
    const last = builtin.length - 1;
    const rows = [];
    builtin.forEach(([limit, fee], i) => {
      if (i < last) {
        rows.push([
          `deal.feeLim${i + 1}`,
          'dealFee',
          `Интервал ${i + 1}: таможенная стоимость до`,
          'num',
          String(limit),
          {
            unit: '₽',
            req: true,
            min: 1,
            max: 1e10,
            hint: `Таможенная стоимость ${i ? `больше границы интервала ${i} и ` : ''}не больше этой суммы — сбор интервала ${i + 1}. Границы должны расти от интервала к интервалу, иначе программа считает по шкале постановления.`,
          },
        ]);
      }
      rows.push([
        `deal.fee${i + 1}`,
        'dealFee',
        i < last ? `Интервал ${i + 1}: сбор` : `Интервал ${i + 1} (дороже последней границы): сбор`,
        'num',
        String(fee),
        {
          unit: '₽',
          req: true,
          min: 0,
          max: 1e6,
          hint: `Сколько платим на таможне за одну декларацию в интервале ${i + 1}. Пример: таможенная стоимость ${this.rub(this._example(i))} ₽ → сбор ${this.rub(fee)} ₽.`,
        },
      ]);
    });
    return rows;
  }

