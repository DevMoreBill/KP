  static OUTLIER = 2;
  static OUTLIER_MIN = 1.2;

  /**
   * Значение из «Значений программы» или запасное.
   * @param {string} key
   * @param {*} fallback
   * @returns {*}
   */
  static def(key, fallback) {
    const value = typeof DEF === 'function' ? DEF(key) : null;
    return value == null ? fallback : value;
  }

  /**
   * Разгрузка на объекте по умолчанию: none — разгружает заказчик, auto — по самому тяжёлому месту, иначе — техника из
   * «Тарифов доставки» (удалённая из тарифов — «не нужна»).
   * @returns {string}
   */
  static unload() {
    const value = String(this.def('log.unload', 'none'));
    if (value === 'auto' || value === 'none') return value;
    return this.techs().some(tech => tech.id === value) ? value : 'none';
  }

  /**
   * Техника разгрузки из «Тарифов доставки».
   * @returns {object[]}
   */
  static techs() {
    const tariffs = LgState.tar || FreightTariffs.of(LgState.saved || {});
    return tariffs && Array.isArray(tariffs.unload) ? tariffs.unload : [];
  }

  /**
   * Срок в пути → «Доставка до заказчика».
   * @returns {boolean}
   */
  static setDays() {
    return this.def('log.setDays', true) !== false;
  }

  /**
   * Сумма доставки в сделку у нового расчёта: auto — по расчёту, manual — своя сумма.
   * @returns {string}
   */
  static mode() {
    return this.def('log.mode', 'auto') === 'manual' ? 'manual' : 'auto';
  }

  /**
   * Валюта своей суммы доставки по умолчанию.
   * @returns {string}
   */
  static manCur() {
    const value = this.def('log.manCur', 'RUB');
    return this.CURS.some(cur => cur[0] === value) ? value : 'RUB';
  }

  /**
   * Агент-экспедитор начисляется и на разгрузку.
   * @returns {boolean}
   */
  static agentUnload() {
    return this.def('log.agentUnload', true) !== false;
  }

  /**
   * «Выброс»: предложение дороже медианы остальных во столько раз не берётся в максимум; 0 — без защиты.
   * @returns {number}
   */
  static outlierK() {
    const value = +this.def('log.outlierK', this.OUTLIER);
    return value > 0 ? Math.max(this.OUTLIER_MIN, value) : 0;
  }

