/**
 * Шаблоны писем клиенту (окно «Отправить КП письмом»): тема и текст с подстановками {номер}, {клиент}, {менеджер}.
 * Список правит администратор: «Настройки → Параметры → Списки выбора → Шаблоны писем». Модуль без зависимостей —
 * его подключает core/lists.js.
 */
export class MailTemplates {
  static LISTS = { 'mail.templates': () => MailTemplates.LIST };
  static LIST = [
    {
      name: 'Коммерческое предложение',
      subject: 'Коммерческое предложение № {номер}',
      body: 'Добрый день!\n\nНаправляем коммерческое предложение № {номер}. Будем рады ответить на вопросы и подготовить варианты.',
    },
    {
      name: 'Напоминание о КП',
      subject: 'КП № {номер} — удалось посмотреть?',
      body: 'Добрый день!\n\nНапоминаем о коммерческом предложении № {номер}. Подскажите, пожалуйста, удалось ли посмотреть и есть ли вопросы? Готовы скорректировать состав и условия.',
    },
    {
      name: 'Обновлённое КП',
      subject: 'Обновлённое коммерческое предложение № {номер}',
      body: 'Добрый день!\n\nНаправляем обновлённое коммерческое предложение № {номер} с учётом ваших пожеланий.',
    },
  ];

  /**
   * Подставить значения в текст шаблона.
   * @param {string} text
   * @param {{number?: string, client?: string, manager?: string}} vars
   * @returns {string}
   */
  static fill(text, vars) {
    const map = { номер: vars.number, клиент: vars.client, менеджер: vars.manager };
    return String(text || '').replace(/\{(номер|клиент|менеджер)\}/g, (all, key) => map[key] || '');
  }
}
