import { Mm } from './mm.js';
import { StationClear } from './station-clear.js';
import { StationEquip } from './station-equip.js';
import { StationMatrix } from './station-matrix.js';
import { StationMods } from './station-mods.js';

const n = v => Mm.text(v);
const dec = v => Mm.dec(v);

/**
 * Свод «как программа компонует станцию» из действующих правил: в «Настройках», во вкладке «Компоновка» и в документе
 * «Инженерные правила и источники».
 */
export class LayoutDigest {
  static n(v) {
    return Mm.text(v);
  }

  /** @returns {{h: string, items: string[]}[]} */
  static sections() {
    const c = this.context();
    return [
      this.goal(c),
      this.aisle(c),
      this.tidy(c),
      this.doors(c),
      this.gates(c),
      this.service(c),
      ...(c.M.ends ? [this.ends(c)] : []),
      this.receivers(c),
      this.pipe(c),
      this.vent(),
      this.cabinets(c),
      this.dgu(c),
      this.pumps(),
      this.mods(c),
    ];
  }

  static context() {
    const [aRec, aMin] = StationClear.aisle();
    return {
      F: StationMatrix.fit(),
      M: StationMatrix.modes(),
      D: StationMatrix.door(),
      Gt: StationMatrix.gate(),
      Sv: StationMatrix.service(),
      A: StationMatrix.access(),
      X: StationMatrix.exits(),
      R: StationMatrix.recv(),
      T: StationMatrix.grp('look'),
      Dg: StationMatrix.grp('dgu'),
      Tk: StationMatrix.grp('tank'),
      Cv: StationMatrix.grp('conv'),
      Pp: StationMatrix.grp('pipe'),
      Cb: StationMatrix.grp('cab'),
      tight: StationLayout.TIGHT,
      aRec,
      aMin,
    };
  }

  static label(kind) {
    return (StationEquip.LABEL[kind] || kind).toLowerCase();
  }

  static OF = {
    compressor: 'ширина компрессора',
    dryer: 'ширина осушителя',
    receiver: 'Ø ресивера',
    pump: 'ширина насоса',
    filter: 'ширина фильтра',
  };

  static pairText(r) {
    const size = this.OF[String(r.of || '').split('.')[0]] || 'размер';
    const base = r.k ? `max(${n(r.base)}; ${dec(r.k)} × ${size})` : n(r.base);
    const close = r.close ? ', вплотную — последним приёмом (исключение)' : '';
    return `${this.label(r.a)} ↔ ${this.label(r.b)} — ${base}, плотно — ${n(r.min)} мм${close}`;
  }

  static wallText(r) {
    const base = r.k ? `max(${n(r.base)}; ${dec(r.k)} × глубина)` : n(r.base);
    return `${this.label(r.kind)} — ${base}, плотно — ${n(r.tight)} мм`;
  }

  static order({ F, M, tight }) {
    const ends = M.ends ? ` или без продольного прохода (если площадь меньше хотя бы на ${n(F.ends)} %)` : '';
    return [
      'без сервисных ворот и дверей, с доступом ко всем сторонам агрегатов (отступ сзади важнее прохода шире допустимого)',
      `с сервисными воротами за агрегатом${ends} — что меньше`,
      ...(M.tight ? [`проход оператора «в крайнем случае» — ${n(tight)} мм`] : []),
      ...(M.cross ? ['агрегат поперёк лицом к входу, вторая дверь оператора за ним'] : []),
      F.wide
        ? `негабарит — шире ${n(F.roadW)} мм (до ${n(F.maxW)} мм), с предупреждением`
        : 'негабарит отключён — ошибка «разделите станцию на два модуля»',
    ];
  }

  static goal(c) {
    const { F, R, T } = c;
    const dense = F.dense
      ? 'плотно — по допустимым отступам и проходу, свободное место раздаётся до рекомендуемых'
      : 'сначала рекомендуемые отступы, затем допустимые';
    const order = this.order(c)
      .map((t, i) => `${i + 1}) ${t}`)
      .join('; ');
    const close = R.close ? 'с замечанием «исключение»' : 'выключено';
    const tidy = T.tidy ? 'аккуратнейший (оценка в «Компоновке»)' : 'первый найденный';
    return {
      h: '1. Цель и порядок подбора',
      items: [
        `Цель — станция в габарите перевозки без спецразрешения: ширина до ${n(F.roadW)} мм, длина до ${n(F.maxL)} мм. Негабарит — только исключение, последним.`,
        `Блок-контейнер — по оборудованию, без запаса: шаг ${n(F.step)} мм, наименьшая площадь пола; ${dense}.`,
        `Варианты по порядку (в ширине перевозки): ${order}.`,
        `Приёмы уплотнения по порядку: допустимые отступы → поворот агрегата на 90° (где разрешён) → ресиверы в два ряда → ресиверы и фильтры вплотную (последним, ${close}) → без прохода у торца.`,
        `Два ряда оборудования — если площадь меньше одного ряда хотя бы на ${n(F.two)} %; ресиверы парами поперёк у торца — если станция короче хотя бы на ${n(F.recv2)} мм.`,
        `Из вариантов равной площади — ${tidy}. Высота внутри — не ниже ${n(F.hWalk)} мм; жалюзи не встают — длиннее до ${n(F.growVent)} мм, конвекторам нет места — до ${n(F.growHeat)} мм.`,
      ],
    };
  }

  static aisle({ M, A, aRec, aMin, tight }) {
    const pairs = StationMatrix.rows('pair').map(r => this.pairText(r));
    const walls = StationMatrix.rows('wall').map(r => this.wallText(r));
    const tightText = M.tight ? `, в крайнем случае ${n(tight)} мм` : '';
    return {
      h: '2. Проход и отступы',
      items: [
        `Проход оператора внутри — всегда (станций «только с сервисными дверями» нет): рекомендуется ${n(aRec)} мм, допустимо ${n(aMin)} мм${tightText}.`,
        `Между соседями по длине: ${pairs.join('; ')}.`,
        `От стены за агрегатом: ${walls.join('; ')}.`,
        `К боку агрегата у торца — проход не меньше ${n(A.side)} мм; сзади меньше ${n(A.back)} мм — обслуживание через сервисные ворота.`,
        `Зазор на коммуникации у стен и под потолком — ${n(StationMatrix.gap())} мм.`,
      ],
    };
  }

  static tidy({ T }) {
    const even = T.even ? 'Одинаковые агрегаты подряд — с равными промежутками.' : 'Промежутки одинаковых — как вышло.';
    const lines = T.lines
      ? 'Сервисные ворота на стене — одной высоты; жалюзи выброса — по общему верху, притока — по общему низу; конвекторы на участке стены — с равным шагом.'
      : '';
    return {
      h: '3. Аккуратность',
      items: [
        `Ряд — по одной лицевой линии, где это ничего не ухудшает: к стене агрегат отходит до рекомендуемого отступа сзади, к проходу — только если проход не уже рекомендуемого; сдвиг до ${n(T.align)} мм.`,
        `${even} ${lines}`,
        'Магистраль — на одной высоте; выходы одинаковых аппаратов — на одной высоте; шкафы на стене — по одной линии верха.',
      ],
    };
  }

  static doors({ D, X }) {
    return {
      h: '4. Двери и выходы',
      items: [
        `Дверь оператора — всегда, одностворчатая ${n(D.w)} × ${n(D.h)} мм в свету, наружу, с доводчиком внутри; над ней — козырёк и прожектор, над выходом — табло «Выход».`,
        `Дверь оператора — одна; вторая — если от дальней точки помещения до выхода больше ${n(X.far)} мм или ряд шкафов длиннее 7 м (ПУЭ, п. 4.1.23). Выходы — дверь оператора, ворота в торце (если перед ними не ресиверы парой) и дверь-жалюзи ДГУ.`,
        `Между проёмами на одной стене — не меньше ${n(D.gap)} мм, от края станции — не меньше ${n(D.edge)} мм; две двери — не ближе ${n(X.dist)} мм друг к другу, где позволяет длина.`,
      ],
    };
  }

  static gates({ Gt }) {
    return {
      h: '5. Ворота в торце',
      items: [
        `Монтажные распашные ворота — всегда в торце (у компрессорной и насосной), по оси торца: ширина = агрегат + ${n(Gt.addW)} мм (не уже ${n(Gt.minW)} мм; во весь торец, если занимают ${dec(Gt.full)} его ширины).`,
        `Высота — по самому высокому оборудованию + ${n(Gt.addH)} мм, в обоих торцах одинаковая, не ниже ${n(Gt.minH)} мм; ворота в обоих торцах — если цепочка длиннее ${n(Gt.twoAt)} мм или агрегат иначе не провезти.`,
      ],
    };
  }

  static service({ A, Sv }) {
    const no = StationMatrix.rows('sides')
      .filter(r => r.door === false)
      .map(r => this.label(r.kind));
    return {
      h: '6. Сервисные ворота',
      items: [
        `Только если агрегат стоит плотно к стене (сзади меньше ${n(A.back)} мм) и иначе его не обслужить: ширина = агрегат + ${n(Sv.addW)} мм (${n(Sv.min)}–${n(Sv.max)} мм), высота = агрегат + ${n(Sv.addH)} мм (не ниже ${n(Sv.minH)} мм); на одной стене — одной высоты.`,
        no.length
          ? `Не делаются: ${no.join(', ')} — монтаж и демонтаж через ворота в торце.`
          : 'Делаются любому виду, стоящему плотно к стене.',
      ],
    };
  }

  static ends({ F, M }) {
    return {
      h: '7. Без продольного прохода (компрессорная)',
      items: [
        `Компрессор у торца по середине ширины: сервисные ворота спереди и сзади, ворота в этом торце; несколько — рядом в ряд от торца, между ними и за последним — не меньше ${n(M.next)} мм, дверь оператора — между компрессорами и за последним.`,
        `Ресиверы — парами поперёк у дальнего торца с воротами там; приток — допускается в створках торцевых ворот. Так — только если с проходом не встаёт в габарит (площадь меньше хотя бы на ${n(F.ends)} %).`,
      ],
    };
  }

  static receivers({ R }) {
    return {
      h: '8. Ресиверы, осушители, фильтры',
      items: [
        'Ресиверы — внутри станции, число — наименьшее допустимое по методике: 900 л → по 500 л (без учёта в Ростехнадзоре) → вплотную; наружу (площадка у торца, ФНП ОРПД, п. 65) — только если внутри не встают.',
        `Два ряда: пара один за другим или парами поперёк у торца — от стен не меньше ${n(R.pairWall)} мм, промежуток в паре — по «Ресивер ↔ ресивер», осмотр заднего — через промежуток не меньше ${n(R.pairSide)} мм.`,
        R.upright
          ? 'Ресивер без указанного исполнения с габаритами «высота × Ø × Ø» — вертикальный.'
          : 'Ресивер без указанного исполнения — как записаны габариты.',
        'Осушитель не проходит по высоте или в плане — два меньших параллельно; фильтры — на трубопроводе по ступеням (до и после осушителя), у осушителя — байпас.',
      ],
    };
  }

  static pipe({ Pp }) {
    return {
      h: '9. Трубопровод',
      items: [
        `Магистраль — вдоль задней стены (ось в ${n(Pp.airY)} мм), по ходу воздуха: компрессоры → аппараты (один вход, один выход) → выход; одинаковые аппараты — параллельно.`,
        `Выход — через дальний торец; в торце на высоте трубы ворота, дверь или дверь-жалюзи ДГУ — на ближайшую свободную стену (от проёма не ближе ${n(Pp.outGap)} мм, от торца ${n(Pp.outEdge)} мм) или над проёмом; снаружи — патрубок ${n(Pp.flange)} мм с фланцем.`,
      ],
    };
  }

  static vent() {
    return {
      h: '10. Вентиляция',
      items: [
        'Выброс горячего воздуха: над сервисными воротами → вверху стены над компрессором → торец у компрессора без ворот → иначе все компрессоры через крышу каналами одного размера. Решётки компрессоров — одного размера у всех; общая вытяжка — у осушителя, своего размера.',
        'Приток — никогда на стене выброса и никогда в створках ворот выброса; одним проёмом, иначе наименьшим числом одинаковых; допускается в створках торцевых и сервисных ворот; не встаёт — приточные вентиляторы, при выбросе на стене — выброс через крышу (исключение).',
      ],
    };
  }

  static cabinets({ Cb, Cv, Dg }) {
    return {
      h: '11. Шкафы и отопление',
      items: [
        `Шкафы — на стене прохода (верх ${n(Cb.top)} мм, низ не ниже ${n(Cb.low)} мм), перед ними — проход обслуживания; не на стыках модулей.`,
        `Конвекторы — у пола на свободных участках стен: между ними ${n(Cv.gap)} мм, от угла ${n(Cv.edge)} мм, свободно перед ${n(Cv.front)} мм (у ДГУ — ${n(Dg.convGap)} / ${n(Dg.convEdge)} / ${n(Dg.convFront)} мм).`,
      ],
    };
  }

  static dgu({ Dg, Tk }) {
    const two = Dg.two
      ? 'две без бака — у торцов радиаторами наружу (выходы через двери-жалюзи, вторая дверь оператора не нужна)'
      : 'две — как три';
    const entry = Tk.gates ? 'ворота в торце' : `дверь ${n(Tk.door)} мм`;
    return {
      h: '12. ДГУ',
      items: [
        `Одна ДГУ — вдоль, посередине ширины (проход с каждой стороны не меньше ${n(Dg.pass)} мм), радиатор — к двери-жалюзи в торце (${n(Dg.rad)} мм); ${two}; от ${n(Dg.across)} (и две с баком) — поперёк, радиаторами к задней стене.`,
        'Выхлоп — у каждой ДГУ свой: глушитель на крыше, если он есть в составе (хоть у одной на крыше — у всех), иначе — через стену; приток — у каждой ДГУ напротив, одинаковый.',
        `Дополнительный бак — в отсеке у торца за перегородкой, прямоугольный по объёму (высота ${n(Tk.h1)} / ${n(Tk.h2)} мм, сначала выше, затем глубже — до ширины помещения); вход — ${entry}, горловина — в нише, топливопровод — по полу.`,
      ],
    };
  }

  static pumps() {
    return {
      h: '13. Насосная',
      items: [
        'Насосы — в ряд у задней стены, между агрегатами — по СП 31.13330.2021, п. 10.15; малые — по два на общей раме; всасывающий и напорный коллекторы — вдоль стены, вход и выход — через торец (в воротах — на свободную стену).',
      ],
    };
  }

  static mods({ F }) {
    const Md = StationMods.M;
    const ws = StationMods.widths();
    return {
      h: '14. Станция из модулей',
      items: [
        `Только кнопкой «Модули…» и с вопросом; до ${n(Md.max)} модулей (больше — по запросу); раскладка — прямоугольник, внутри — одно помещение.`,
        `Модули одной ширины ${n(ws[0])}–${n(ws[ws.length - 1])} мм, длина модуля — от ${n(Md.lMin)} до ${n(F.maxL)} мм; крупные агрегаты — сначала в один ряд модулей (торец к торцу), два ряда — только если иначе не встаёт.`,
        'Оборудование — целиком в своём модуле (на стыках ничего нет): на производстве собрано и проверено, на перевозку — расстыковка трубопровода и кабелей, на объекте — быстрая стыковка; в ТЗ — разъёмные соединения каждого стыка с маркировкой.',
      ],
    };
  }

  /** HTML: разделы со списками. */
  static html() {
    const list = items => items.map(t => `<li>${esc(t)}</li>`).join('');
    return this.sections()
      .map(s => `<p class="ld-h"><b>${esc(s.h)}</b></p><ul class="ld-l">${list(s.items)}</ul>`)
      .join('');
  }
}
