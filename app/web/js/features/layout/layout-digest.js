import { LayoutMode } from './layout-mode.js';
import { Mm } from './mm.js';
import { StationClear } from './station-clear.js';
import { StationEquip } from './station-equip.js';
import { StationMatrix } from './station-matrix.js';
import { StationMods } from './station-mods.js';
import { StationNorms } from './station-norms.js';
import { esc } from '../../core/util.js';

/**
 * Свод «как программа компонует станцию» из действующих правил: в «Настройках», во вкладке «Компоновка» и в документе
 * «Инженерные правила и источники».
 */
export class LayoutDigest {
  /** @returns {{h: string, items: string[]}[]} */
  static sections() {
    const ctx = this.context();
    return [
      this._goal(ctx),
      this.aisle(ctx),
      this.tidy(ctx),
      this.doors(ctx),
      this.gates(ctx),
      this.service(ctx),
      ...(ctx.modes.ends ? [this.ends(ctx)] : []),
      this.receivers(ctx),
      this.pipe(ctx),
      this.vent(),
      this.cabinets(ctx),
      this.dgu(ctx),
      this.pumps(),
      this.mods(ctx),
    ];
  }

  /** Значения матрицы, общие для всех разделов сводки. */
  static context() {
    const [aRec, aMin] = StationClear.aisle();
    return {
      fit: StationMatrix.fit(),
      modes: StationMatrix.modes(),
      door: StationMatrix.door(),
      gate: StationMatrix.gate(),
      service: StationMatrix.service(),
      access: StationMatrix.access(),
      exits: StationMatrix.exits(),
      recv: StationMatrix.recv(),
      look: StationMatrix.grp('look'),
      dgu: StationMatrix.grp('dgu'),
      tank: StationMatrix.grp('tank'),
      conv: StationMatrix.grp('conv'),
      pipe: StationMatrix.grp('pipe'),
      cab: StationMatrix.grp('cab'),
      tight: LayoutMode.TIGHT,
      aRec,
      aMin,
    };
  }

  /** Название вида оборудования строчными буквами. */
  static label(kind) {
    return (StationEquip.LABEL[kind] || kind).toLowerCase();
  }

  static WIDTH_OF = {
    compressor: 'ширина компрессора',
    dryer: 'ширина осушителя',
    receiver: 'Ø ресивера',
    pump: 'ширина насоса',
    filter: 'ширина фильтра',
  };

  static _pairText(row) {
    const size = this.WIDTH_OF[String(row.of || '').split('.')[0]] || 'размер';
    const base = row.k ? `max(${Mm.text(row.base)}; ${Mm.dec(row.k)} × ${size})` : Mm.text(row.base);
    const close = row.close ? ', вплотную — последним приёмом (исключение)' : '';
    return `${this.label(row.a)} ↔ ${this.label(row.b)} — ${base}, плотно — ${Mm.text(row.min)} мм${close}`;
  }

  static _wallText(row) {
    const base = row.k ? `max(${Mm.text(row.base)}; ${Mm.dec(row.k)} × глубина)` : Mm.text(row.base);
    return `${this.label(row.kind)} — ${base}, плотно — ${Mm.text(row.tight)} мм`;
  }

  /** Раздел сводки «Порядок подбора». */
  static order({ fit, modes, tight }) {
    const ends = modes.ends
      ? ` или без продольного прохода (если площадь меньше хотя бы на ${Mm.text(fit.ends)} %)`
      : '';
    return [
      'без сервисных ворот и дверей, с доступом ко всем сторонам агрегатов (отступ сзади важнее прохода шире допустимого)',
      `с сервисными воротами за агрегатом${ends} — что меньше`,
      ...(modes.tight ? [`проход оператора «в крайнем случае» — ${Mm.text(tight)} мм`] : []),
      ...(modes.cross ? ['агрегат поперёк лицом к входу, вторая дверь оператора за ним'] : []),
      fit.wide
        ? `негабарит — шире ${Mm.text(fit.roadW)} мм (до ${Mm.text(fit.maxW)} мм), с предупреждением`
        : 'негабарит отключён — ошибка «разделите станцию на два модуля»',
    ];
  }

  static _goal(ctx) {
    const { fit, recv, look } = ctx;
    const dense = fit.dense
      ? 'плотно — по допустимым отступам и проходу, свободное место раздаётся до рекомендуемых'
      : 'сначала рекомендуемые отступы, затем допустимые';
    const order = this.order(ctx)
      .map((item, i) => `${i + 1}) ${item}`)
      .join('; ');
    const close = recv.close ? 'с замечанием «исключение»' : 'выключено';
    const tidy = look.tidy ? 'аккуратнейший (оценка в «Компоновке»)' : 'первый найденный';
    return {
      h: '1. Цель и порядок подбора',
      items: [
        `Цель — станция в габарите перевозки без спецразрешения: ширина до ${Mm.text(fit.roadW)} мм, длина до ${Mm.text(fit.maxL)} мм. Негабарит — только исключение, последним.`,
        `Блок-контейнер — по оборудованию, без запаса: шаг ${Mm.text(fit.step)} мм, наименьшая площадь пола; ${dense}.`,
        `Варианты по порядку (в ширине перевозки): ${order}.`,
        `Приёмы уплотнения по порядку: допустимые отступы → поворот агрегата на 90° (где разрешён) → ресиверы в два ряда → ресиверы и фильтры вплотную (последним, ${close}) → без прохода у торца.`,
        `Два ряда оборудования — если площадь меньше одного ряда хотя бы на ${Mm.text(fit.two)} %; ресиверы парами поперёк у торца — если станция короче хотя бы на ${Mm.text(fit.recv2)} мм.`,
        `Из вариантов равной площади — ${tidy}. Высота внутри — не ниже ${Mm.text(fit.hWalk)} мм; жалюзи не встают — длиннее до ${Mm.text(fit.growVent)} мм, конвекторам нет места — до ${Mm.text(fit.growHeat)} мм.`,
      ],
    };
  }

  /** Раздел сводки «Проходы». */
  static aisle({ modes, access, aRec, aMin, tight }) {
    const pairs = StationMatrix.rows('pair').map(row => this._pairText(row));
    const walls = StationMatrix.rows('wall').map(row => this._wallText(row));
    const tightText = modes.tight ? `, в крайнем случае ${Mm.text(tight)} мм` : '';
    return {
      h: '2. Проход и отступы',
      items: [
        `Проход оператора внутри — всегда (станций «только с сервисными дверями» нет): рекомендуется ${Mm.text(aRec)} мм, допустимо ${Mm.text(aMin)} мм${tightText}.`,
        `Между соседями по длине: ${pairs.join('; ')}.`,
        `От стены за агрегатом: ${walls.join('; ')}.`,
        `К боку агрегата у торца — проход не меньше ${Mm.text(access.side)} мм; сзади меньше ${Mm.text(access.back)} мм — обслуживание через сервисные ворота.`,
        `Зазор на коммуникации у стен и под потолком — ${Mm.text(StationMatrix.gap())} мм.`,
      ],
    };
  }

  /** Раздел сводки «Аккуратная компоновка». */
  static tidy({ look }) {
    const even = look.even
      ? 'Одинаковые агрегаты подряд — с равными промежутками.'
      : 'Промежутки одинаковых — как вышло.';
    const lines = look.lines
      ? 'Сервисные ворота на стене — одной высоты; жалюзи выброса — по общему верху, притока — по общему низу; конвекторы на участке стены — с равным шагом.'
      : '';
    return {
      h: '3. Аккуратность',
      items: [
        `Ряд — по одной лицевой линии, где это ничего не ухудшает: к стене агрегат отходит до рекомендуемого отступа сзади, к проходу — только если проход не уже рекомендуемого; сдвиг до ${Mm.text(look.align)} мм.`,
        `${even} ${lines}`,
        'Магистраль — на одной высоте; выходы одинаковых аппаратов — на одной высоте; шкафы на стене — по одной линии верха.',
      ],
    };
  }

  /** Раздел сводки «Двери и выходы». */
  static doors({ door, exits }) {
    return {
      h: '4. Двери и выходы',
      items: [
        `Дверь оператора — всегда, одностворчатая ${Mm.text(door.w)} × ${Mm.text(door.h)} мм в свету, наружу, с доводчиком внутри; над ней — козырёк и прожектор, над выходом — табло «Выход».`,
        `Дверь оператора — одна; вторая — если от дальней точки помещения до выхода больше ${Mm.text(exits.far)} мм или ряд шкафов длиннее ${StationNorms.shieldText()} (ПУЭ, п. 4.1.23). Выходы — дверь оператора, ворота в торце (если перед ними не ресиверы парой) и дверь-жалюзи ДГУ.`,
        `Между проёмами на одной стене — не меньше ${Mm.text(door.gap)} мм, от края станции — не меньше ${Mm.text(door.edge)} мм; две двери — не ближе ${Mm.text(exits.dist)} мм друг к другу, где позволяет длина.`,
      ],
    };
  }

  /** Раздел сводки «Ворота». */
  static gates({ gate }) {
    return {
      h: '5. Ворота в торце',
      items: [
        `Монтажные распашные ворота — всегда в торце (у компрессорной и насосной), по оси торца: ширина = агрегат + ${Mm.text(gate.addW)} мм (не уже ${Mm.text(gate.minW)} мм; во весь торец, если занимают ${Mm.dec(gate.full)} его ширины).`,
        `Высота — по самому высокому оборудованию + ${Mm.text(gate.addH)} мм, в обоих торцах одинаковая, не ниже ${Mm.text(gate.minH)} мм; ворота в обоих торцах — если цепочка длиннее ${Mm.text(gate.twoAt)} мм или агрегат иначе не провезти.`,
      ],
    };
  }

  /** Раздел сводки «Обслуживание». */
  static service({ access, service }) {
    const noDoor = StationMatrix.rows('sides')
      .filter(row => row.door === false)
      .map(row => this.label(row.kind));
    return {
      h: '6. Сервисные ворота',
      items: [
        `Только если агрегат стоит плотно к стене (сзади меньше ${Mm.text(access.back)} мм) и иначе его не обслужить: ширина = агрегат + ${Mm.text(service.addW)} мм (${Mm.text(service.min)}–${Mm.text(service.max)} мм), высота = агрегат + ${Mm.text(service.addH)} мм (не ниже ${Mm.text(service.minH)} мм); на одной стене — одной высоты.`,
        noDoor.length
          ? `Не делаются: ${noDoor.join(', ')} — монтаж и демонтаж через ворота в торце.`
          : 'Делаются любому виду, стоящему плотно к стене.',
      ],
    };
  }

  /** Раздел сводки «Без продольного прохода». */
  static ends({ fit, modes }) {
    return {
      h: '7. Без продольного прохода (компрессорная)',
      items: [
        `Компрессор у торца по середине ширины: сервисные ворота спереди и сзади, ворота в этом торце; несколько — рядом в ряд от торца, между ними и за последним — не меньше ${Mm.text(modes.next)} мм, дверь оператора — между компрессорами и за последним.`,
        `Ресиверы — парами поперёк у дальнего торца с воротами там; приток — допускается в створках торцевых ворот. Так — только если с проходом не встаёт в габарит (площадь меньше хотя бы на ${Mm.text(fit.ends)} %).`,
      ],
    };
  }

  /** Раздел сводки «Ресиверы». */
  static receivers({ recv }) {
    return {
      h: '8. Ресиверы, осушители, фильтры',
      items: [
        'Ресиверы — внутри станции, число — наименьшее допустимое по методике: 900 л → по 500 л (без учёта в Ростехнадзоре) → вплотную; наружу (площадка у торца, ФНП ОРПД, п. 65) — только если внутри не встают.',
        `Два ряда: пара один за другим или парами поперёк у торца — от стен не меньше ${Mm.text(recv.pairWall)} мм, промежуток в паре — по «Ресивер ↔ ресивер», осмотр заднего — через промежуток не меньше ${Mm.text(recv.pairSide)} мм.`,
        recv.upright
          ? 'Ресивер без указанного исполнения с габаритами «высота × Ø × Ø» — вертикальный.'
          : 'Ресивер без указанного исполнения — как записаны габариты.',
        'Осушитель не проходит по высоте или в плане — два меньших параллельно; фильтры — на трубопроводе по ступеням (до и после осушителя), у осушителя — байпас.',
      ],
    };
  }

  /** Раздел сводки «Трубы». */
  static pipe({ pipe }) {
    return {
      h: '9. Трубопровод',
      items: [
        `Магистраль — вдоль задней стены (ось в ${Mm.text(pipe.airY)} мм), по ходу воздуха: компрессоры → аппараты (один вход, один выход) → выход; одинаковые аппараты — параллельно.`,
        `Выход — через дальний торец; в торце на высоте трубы ворота, дверь или дверь-жалюзи ДГУ — на ближайшую свободную стену (от проёма не ближе ${Mm.text(pipe.outGap)} мм, от торца ${Mm.text(pipe.outEdge)} мм) или над проёмом; снаружи — патрубок ${Mm.text(pipe.flange)} мм с фланцем.`,
      ],
    };
  }

  /** Раздел сводки «Вентиляция». */
  static vent() {
    return {
      h: '10. Вентиляция',
      items: [
        'Выброс горячего воздуха: над сервисными воротами → вверху стены над компрессором → торец у компрессора без ворот → иначе все компрессоры через крышу каналами одного размера. Решётки компрессоров — одного размера у всех; общая вытяжка — у осушителя, своего размера.',
        'Приток — никогда на стене выброса и никогда в створках ворот выброса; одним проёмом, иначе наименьшим числом одинаковых; допускается в створках торцевых и сервисных ворот; не встаёт — приточные вентиляторы, при выбросе на стене — выброс через крышу (исключение).',
      ],
    };
  }

  /** Раздел сводки «Шкафы и конвекторы». */
  static cabinets({ cab, conv, dgu }) {
    return {
      h: '11. Шкафы и отопление',
      items: [
        `Шкафы — на стене прохода (верх ${Mm.text(cab.top)} мм, низ не ниже ${Mm.text(cab.low)} мм), перед ними — проход обслуживания; не на стыках модулей.`,
        `Конвекторы — у пола на свободных участках стен: между ними ${Mm.text(conv.gap)} мм, от угла ${Mm.text(conv.edge)} мм, свободно перед ${Mm.text(conv.front)} мм (у ДГУ — ${Mm.text(dgu.convGap)} / ${Mm.text(dgu.convEdge)} / ${Mm.text(dgu.convFront)} мм).`,
      ],
    };
  }

  /** Раздел сводки «ДГУ и бак». */
  static dgu({ dgu, tank }) {
    const two = dgu.two
      ? 'две без бака — у торцов радиаторами наружу (выходы через двери-жалюзи, вторая дверь оператора не нужна)'
      : 'две — как три';
    const entry = tank.gates ? 'ворота в торце' : `дверь ${Mm.text(tank.door)} мм`;
    return {
      h: '12. ДГУ',
      items: [
        `Одна ДГУ — вдоль, посередине ширины (проход с каждой стороны не меньше ${Mm.text(dgu.pass)} мм), радиатор — к двери-жалюзи в торце (${Mm.text(dgu.rad)} мм); ${two}; от ${Mm.text(dgu.across)} (и две с баком) — поперёк, радиаторами к задней стене.`,
        'Выхлоп — у каждой ДГУ свой: глушитель на крыше, если он есть в составе (хоть у одной на крыше — у всех), иначе — через стену; приток — у каждой ДГУ напротив, одинаковый.',
        `Дополнительный бак — в отсеке у торца за перегородкой, прямоугольный по объёму (высота ${Mm.text(tank.h1)} / ${Mm.text(tank.h2)} мм, сначала выше, затем глубже — до ширины помещения); вход — ${entry}, горловина — в нише, топливопровод — по полу.`,
      ],
    };
  }

  /** Раздел сводки «Насосы». */
  static pumps() {
    return {
      h: '13. Насосная',
      items: [
        'Насосы — в ряд у задней стены, между агрегатами — по СП 31.13330.2021, п. 10.15; малые — по два на общей раме; всасывающий и напорный коллекторы — вдоль стены, вход и выход — через торец (в воротах — на свободную стену).',
      ],
    };
  }

  /** Раздел сводки «Модули». */
  static mods({ fit }) {
    const rules = StationMods.RULES;
    const widths = StationMods.widths();
    return {
      h: '14. Станция из модулей',
      items: [
        `Только кнопкой «Модули…» и с вопросом; до ${Mm.text(rules.max)} модулей (больше — по запросу); раскладка — прямоугольник, внутри — одно помещение.`,
        `Модули одной ширины ${Mm.text(widths[0])}–${Mm.text(widths[widths.length - 1])} мм, длина модуля — от ${Mm.text(rules.lMin)} до ${Mm.text(fit.maxL)} мм; крупные агрегаты — сначала в один ряд модулей (торец к торцу), два ряда — только если иначе не встаёт.`,
        'Оборудование — целиком в своём модуле (на стыках ничего нет): на производстве собрано и проверено, на перевозку — расстыковка трубопровода и кабелей, на объекте — быстрая стыковка; в ТЗ — разъёмные соединения каждого стыка с маркировкой.',
      ],
    };
  }

  /** HTML: разделы со списками. */
  static html() {
    const list = items => items.map(item => `<li>${esc(item)}</li>`).join('');
    return this.sections()
      .map(section => `<p class="ld-h"><b>${esc(section.h)}</b></p><ul class="ld-l">${list(section.items)}</ul>`)
      .join('');
  }
}
